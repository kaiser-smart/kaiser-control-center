import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdirSync, existsSync, cpSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { target, fileHashes, sha256 } from "./pwa-release.mjs";
import { verifyPackage } from "./pwa-package-integrity.mjs";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const git=args=>execFileSync("git",args,{cwd:root,encoding:"utf8",maxBuffer:30*1024*1024}).trim();
assert.equal(git(["status","--porcelain"]),"","Commit all reviewed changes before packaging");
assert.equal(git(["branch","--show-current"]),target.branch);
const head=git(["rev-parse","HEAD"]), base="c37cd96b3313ad5d8678e1018f76bf1b9d98f72e";
assert.equal(git(["rev-parse","HEAD^"]),base,"Package release must be one self-contained commit on reviewed base");
assert.equal(git(["diff",base,"HEAD","--","wrangler.toml"]),"","Cloudflare bindings must remain unchanged");
const version=JSON.parse(readFileSync(path.join(root,"package.json"))).version;
const buildMeta=JSON.parse(readFileSync(path.join(root,"dist/src/data/buildMeta.js"),"utf8").match(/= (\{[\s\S]*\});/)[1]);
assert.equal(buildMeta.commit,head.slice(0,7)); assert.equal(buildMeta.version,version); assert.equal(buildMeta.branch,target.branch);
const destination=path.resolve(process.argv[2] || path.join(root,"output",`SMART_ODPADY_PWA_${version}`));
assert.ok(!existsSync(destination),"Destination already exists; preserve previous evidence");
mkdirSync(path.join(destination,"tools"),{recursive:true});
cpSync(path.join(root,"dist"),path.join(destination,"dist"),{recursive:true});
const patch=execFileSync("git",["diff","--binary","--full-index","--unified=0",base,head],{cwd:root,maxBuffer:30*1024*1024});
writeFileSync(path.join(destination,"changes.patch"),patch);
for (const name of ["pwa-release.mjs","pwa-cloudflare.mjs","pwa-package-integrity.mjs","pwa-postdeploy.mjs"]) cpSync(path.join(root,"scripts",name),path.join(destination,"tools",name));
for (const name of ["pripravit.mjs","nasadit.mjs","vratit.mjs"]) cpSync(path.join(root,"scripts/pwa-package",name),path.join(destination,name));
for (const name of ["PWA_IPHONE_AUDIT.md","PWA_IPHONE_NASAZENI.md","PWA_IPHONE_INSTALACE.md"]) cpSync(path.join(root,"docs",name),path.join(destination,name));
const files=fileHashes(path.join(root,"dist"));
const assets=Object.fromEntries(["/icons/apple-touch-icon.png","/icons/icon-192.png","/icons/icon-512.png","/src/app.js","/src/styles.css","/src/data/sessionGuard.js","/src/data/versionInfo.js"].map(url=>[url,files[url.slice(1)]]));
const release={schema:2,head,base,tree:git(["rev-parse","HEAD^{tree}"]),version,baseVersion:"0.1.829",buildDate:buildMeta.backupDate,account:target.account,project:target.project,rollbackDeployment:"863bae5e-a256-4aa9-a6ba-7a6b552512d2",rollbackAvailability:"requires live preflight",patchSha256:sha256(patch),commitObject:execFileSync("git",["cat-file","commit",head],{cwd:root}).toString("base64"),files,assets,routes:JSON.parse(readFileSync(path.join(root,"dist/route-manifest.json"))).routes.map(r=>r.path)};
writeFileSync(path.join(destination,"release.json"),JSON.stringify(release,null,2)+'\n');
const evidence=path.join(root,"output/pwa-final");
mkdirSync(path.join(destination,"verification"));
for(const name of ["tests.json","browser.json","functions.json","cloudflare-access.json","production.json","security.json"]) {
 assert.ok(existsSync(path.join(evidence,name)),`Missing verification: ${name}`);
 cpSync(path.join(evidence,name),path.join(destination,"verification",name));
}
if (existsSync(path.join(evidence,"restoration.json"))) cpSync(path.join(evidence,"restoration.json"),path.join(destination,"verification/restoration.json"));
const all=fileHashes(destination);
writeFileSync(path.join(destination,"SHA256SUMS"),Object.entries(all).map(([file,sha])=>`${sha}  ${file}`).join('\n')+'\n');
console.log(JSON.stringify({directory:destination,version,head,integrity:verifyPackage(destination)}));
