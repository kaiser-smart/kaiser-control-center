import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const migrationsRoot = join(root, "migrations", "modular");
const outputPath = join(root, "functions", "_lib", "database-table-domains.js");
const domains = ["core", "messages", "audit", "archive"];
const tablesByDomain = {};
const tableOwners = new Map();

for (const domain of domains) {
  const directory = join(migrationsRoot, domain);
  const tables = new Set();
  for (const file of readdirSync(directory).filter((name) => name.endsWith(".sql")).sort()) {
    const sql = readFileSync(join(directory, file), "utf8");
    for (const match of sql.matchAll(/CREATE TABLE(?: IF NOT EXISTS)?\s+["`[]?([a-z][a-z0-9_]*)/gi)) {
      tables.add(match[1]);
    }
  }
  tablesByDomain[domain] = [...tables].sort();
  for (const table of tablesByDomain[domain]) {
    const existing = tableOwners.get(table);
    if (existing && existing !== domain) {
      throw new Error(`Tabulka ${table} je současně v ${existing} a ${domain}.`);
    }
    tableOwners.set(table, domain);
  }
}

const lines = [
  "// Generated by scripts/generate-database-table-domains.mjs.",
  "// Do not edit manually; table ownership comes from migrations/modular.",
  "",
  "export const DATABASE_TABLES = Object.freeze({"
];
for (const domain of domains) {
  lines.push(`  ${domain}: Object.freeze(${JSON.stringify(tablesByDomain[domain], null, 2).replaceAll("\n", "\n  ")}),`);
}
lines.push("});", "");
lines.push("export const DATABASE_TABLE_DOMAINS = Object.freeze(Object.fromEntries(");
lines.push("  Object.entries(DATABASE_TABLES).flatMap(([domain, tables]) => tables.map((table) => [table, domain]))");
lines.push("));", "");

writeFileSync(outputPath, `${lines.join("\n")}\n`);
process.stdout.write(`${JSON.stringify({ outputPath, counts: Object.fromEntries(domains.map((domain) => [domain, tablesByDomain[domain].length])) }, null, 2)}\n`);
